#!/usr/bin/env node
// Regenerate config/words-en.txt: lower-case English words found in at least MIN_DOCS postings
// from the job boards (INSPIRE, AJO, MathJobs). crawler/lib/garble.mjs uses it to tell real text
// from legacy-font gibberish. A word list carries no advert text.
// Usage: node tools/make-wordlist.mjs [.out/postings.json]
import { readFile, writeFile } from 'node:fs/promises';

const MIN_DOCS = 3;
const { postings } = JSON.parse(await readFile(process.argv[2] ?? '.out/postings.json', 'utf8'));
const df = new Map();
for (const p of postings) {
  if (!p.sources.some((s) => ['inspire', 'ajo', 'mathjobs'].includes(s.source))) continue;
  const words = new Set(`${p.title} ${p.body}`.toLowerCase().match(/\b[a-z]{2,24}\b/g) ?? []);
  for (const w of words) df.set(w, (df.get(w) ?? 0) + 1);
}
const list = [...df].filter(([, n]) => n >= MIN_DOCS).map(([w]) => w).sort();
await writeFile('config/words-en.txt', `# Generated by tools/make-wordlist.mjs (words in >= ${MIN_DOCS} board postings). Don't edit by hand.\n${list.join('\n')}\n`);
console.error(`${list.length} words -> config/words-en.txt`);
